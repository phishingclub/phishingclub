// packageTypeIconKey maps a baitbox package type to its menu icon key, so a card
// shows the same icon the sidebar uses for that resource.
export function packageTypeIconKey(type) {
	switch (type) {
		case 'page':
			return 'pages';
		case 'email':
			return 'emails_overview';
		case 'domain':
			return 'domains_overview';
		case 'proxy':
			return 'proxy';
		case 'script':
			return 'script';
		case 'asset':
			return 'assets';
		case 'attachment':
			return 'attachments';
		case 'smtp':
			return 'smtp_configurations';
		case 'webhook':
			return 'webhooks';
		case 'remotebrowser':
			return 'remote_browser';
		case 'template':
			return 'campaign_templates';
		case 'reporttemplate':
			return 'campaign_templates';
		case 'allowdeny':
			return 'filters';
		case 'identifier':
			return 'api_senders';
		default:
			return 'pages';
	}
}
